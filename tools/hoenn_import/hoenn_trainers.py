#!/usr/bin/env python3
"""Emerald's trainers for RFVF+: their data, and their scripts on the imported Hoenn maps.
Usage (Git Bash, from the repo root):
    uv run --no-project --with pyelftools python tools/hoenn_import/hoenn_trainers.py [--scripts]
Data (always, generated files, do not edit them):
    Emerald's trainers keep Emerald's order in the Hoenn block of trainer ids: id = TRAINER_HOENN_START + Emerald id - 1
    (Emerald's TRAINER_X names; their defeat flags live in the extended flags, see TRAINER_FLAG in flags.h).
    include/constants/opponents_hoenn.h, src/data/trainers_hoenn.h (official French names, read from the French ROM's
    gTrainers, found by fingerprint), src/data/trainer_parties_hoenn.h (Emerald's parties as they are),
    src/data/vs_seeker_hoenn.h (Emerald's rematch table: the VS Seeker gives the next unbeaten party, as Match Call).
    Classes map to this repo's R/S ones (RS_X, else X in the R/S block); the classes and pics Emerald alone has were
    added once by hand (TRAINER_CLASS_WINSTRATE..., TRAINER_PIC_CHAMPION_WALLACE...).
--scripts: the trainers the import left as silent stubs in data/maps/*/scripts.inc ("@ trainer #", and the NPC stubs
    whose Emerald script starts a battle) get Emerald's script: Match Call registration dropped, rematches through
    the VS Seeker (Emerald's own rematch texts), the after-battle script of a gym trainer dropped (gym mechanisms come
    with the gym scripts). Their objects see the player again (map.json: Emerald's trainer type and sight), and the
    buried trainers the import left out (Route 113 ash, Lavaridge Gym sand) are added. The texts come after:
    hoenn_texts.py <prefix> --write for each map.
Inputs, read only: ../pokeemerald (with its built pokeemerald.gba + .elf) and the French Emerald ROM (BPEF).
"""
import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hoenn_texts import charmap  # noqa: E402
from hoenn_decisions import RENAMES  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
HOENN_START = 768  # MAX_TRAINERS_COUNT: Kanto's trainers and flags stay where they are
GENERATED = "// Generated by tools/hoenn_import/hoenn_trainers.py from pokeemerald: do not edit.\n"
# Emerald pics this repo already has under another name (byte-identical)
# NPCs (no sight) whose Emerald script is a plain trainer battle; gym leaders, the Elite Four and Steven come with
# their own scripts (badges, TMs, the League)
TALK_TO_BATTLE = {"HoennVictoryRoad_1F_EventScript_ExitWally"}
PIC_ALIASES = {"BRENDAN": "EM_BRENDAN", "MAY": "EM_MAY", "RS_BRENDAN": "RS_BRENDAN_1", "RS_MAY": "RS_MAY_1",
               "MAGMA_ADMIN": "MAGMA_ADMIN_M", "STEVEN": "CHAMPION_STEVEN"}


def read(p):
    return Path(p).read_text(encoding="utf-8")


def write(p, text):
    with open(REPO / p, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote", p)


def defines(text, prefix):
    return {m[0]: int(m[1], 0) for m in re.findall(r"^#define %s(\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b" % prefix, text, re.M)}


def emerald_trainers(em):
    ids = sorted((v, k) for k, v in defines(read(em / "include/constants/opponents.h"), "TRAINER_").items()
                 if k not in ("NONE", "TRAINERS_COUNT", "MAX_TRAINERS_COUNT", "PARTNER_STEVEN"))
    assert [v for v, _ in ids] == list(range(1, len(ids) + 1)), "Emerald trainer ids are not 1..N"
    entries = {}
    for name, body in re.findall(r"^    \[TRAINER_(\w+)\] =\s*\{\n(.*?)^    \},", read(em / "src/data/trainers.h"),
                                 re.M | re.S):
        entries[name] = dict(re.findall(r"^\s*\.(\w+) = (.*),$", body, re.M))
    return [k for _, k in ids], entries


def french_names(em, fr_rom, count):
    """Trainer names of the French ROM's gTrainers (40-byte entries, same order and bytes but name and party)."""
    from elftools.elf.elffile import ELFFile
    en, fr = (em / "pokeemerald.gba").read_bytes(), fr_rom.read_bytes()
    assert fr[0xAC:0xB0] == b"BPEF", "expected French Emerald (BPEF)"
    sym = {s.name: s["st_value"] for s in ELFFile(open(em / "pokeemerald.elf", "rb")).get_section_by_name(".symtab")
           .iter_symbols()}
    t = sym["gTrainers"] - 0x08000000
    e = en[t + 40:t + 80]
    hits = [m.start() - 40 for m in re.finditer(re.escape(e[:4]) + b".{12}" + re.escape(e[0x10:0x24]), fr, re.S)]
    assert len(hits) == 1, "French gTrainers not found"
    f = hits[0]
    assert all(fr[f + 40 * i:f + 40 * i + 4] == en[t + 40 * i:t + 40 * i + 4] for i in range(count + 1))
    chars = charmap()[0]
    return [''.join(chars[b] for b in fr[f + 40 * i + 4:f + 40 * i + 16].split(b"\xff")[0]) for i in range(1, count + 1)]


def gen_data(em, fr_rom):
    names, entries = emerald_trainers(em)
    fr = french_names(em, fr_rom, len(names))
    here = read(REPO / "include/constants/trainers.h")
    classes, pics = defines(here, "TRAINER_CLASS_"), defines(here, "TRAINER_PIC_")

    def cls(c):
        c = c.replace("TRAINER_CLASS_", "")
        r = "RS_" + c if "RS_" + c in classes else c
        assert r in classes and (r.startswith("RS_") or classes[r] <= 56 or classes[r] > 106), "class " + c
        return "TRAINER_CLASS_" + r

    def pic(p):
        p = PIC_ALIASES.get(p[12:], p[12:])
        r = "RS_" + p if "RS_" + p in pics else p
        assert r in pics, "pic " + p
        return "TRAINER_PIC_" + r

    consts, data = [], []
    for i, (n, name) in enumerate(zip(names, fr)):
        consts.append("#define TRAINER_%-28s %d\n" % (n, HOENN_START + i))
        e = entries[n]
        data.append("    [TRAINER_%s] = {\n" % n + "".join("        .%s = %s,\n" % kv for kv in (
            ("trainerClass", cls(e["trainerClass"])),
            ("encounterMusic_gender", e["encounterMusic_gender"]),
            ("trainerPic", pic(e["trainerPic"])),
            ("trainerName", '_("%s")' % name),
            ("items", e["items"]),
            ("doubleBattle", e["doubleBattle"]),
            ("aiFlags", e["aiFlags"]),
            ("party", e["party"].replace("sParty_", "sPartyHoenn_")))) + "    },\n")
    write("include/constants/opponents_hoenn.h", GENERATED + "// Emerald's trainers, in Emerald's order.\n"
          "#ifndef GUARD_CONSTANTS_OPPONENTS_HOENN_H\n#define GUARD_CONSTANTS_OPPONENTS_HOENN_H\n\n"
          "#define TRAINER_HOENN_START %d\n" % HOENN_START + "".join(consts) +
          "#define HOENN_TRAINERS_COUNT %d\n\n#endif  // GUARD_CONSTANTS_OPPONENTS_HOENN_H\n" % len(names))
    write("src/data/trainers_hoenn.h", GENERATED + "".join(data))
    write("src/data/trainer_parties_hoenn.h", GENERATED +
          read(em / "src/data/trainer_parties.h").replace("sParty_", "sPartyHoenn_"))
    rematches = []
    for ids in re.findall(r"= REMATCH\(((?:TRAINER_\w+, ){5})MAP_\w+\)", read(em / "src/battle_setup.c")):
        ids = ids.rstrip(", ").split(", ")
        if len(set(ids)) > 1:  # the Elite Four and the Champion have no rematch
            rematches.append("   { {%s} },\n" % ", ".join(ids))
    write("src/data/vs_seeker_hoenn.h", GENERATED + "// Emerald's gRematchTable (the Elite Four and the Champion left out)\n"
          + "".join(rematches))


# --- scripts ---------------------------------------------------------------------------------------------------

def rename(text):
    for old, new in RENAMES.items():
        text = re.sub(r"(?<![/\w])%s_" % old, new + "_", text)
    return text


def blocks(text):
    """label -> its lines up to its first end/return (Emerald scripts.inc)."""
    out, cur = {}, None
    for line in text.splitlines():
        m = re.match(r"^(\w+)::", line)
        if m:
            cur = m.group(1)
            out[cur] = []
            continue
        if re.match(r"^\w+:\s*$", line):  # a text
            cur = None
        if cur and line.strip() and (not out[cur] or out[cur][-1].strip() not in ("end", "return")):
            out[cur].append(line)
    return out


def convert(label, lines, all_blocks, done):
    """Emerald's trainer script `label` (+ its rematch script) for this repo; None if it is not a trainer's."""
    if not lines or not lines[0].strip().startswith("trainerbattle"):
        return None
    out, follow = [], []
    for line in lines:
        s = line.strip()
        m = re.match(r"(trainerbattle_(single|double)) (.*)", s)
        raw = re.match(r"trainerbattle TRAINER_BATTLE_CONTINUE_SCRIPT, (\w+), \w+, (\w+), (\w+), \w+$", s)
        if m:  # no after-battle script: Match Call registration, gym mechanisms (gym scripts)
            args = m.group(3).split(", ")
            line = "\t%s %s" % (m.group(1), ", ".join(args[:3 if m.group(2) == "single" else 4]))
        elif raw:  # Lavaridge Gym's buried trainers
            line = "\ttrainerbattle_single %s" % ", ".join(raw.groups())
        elif re.match(r"setvar VAR_0x8004, TRAINER_|specialvar VAR_RESULT, IsTrainerRegistered|"
                      r"goto_if_eq VAR_RESULT, FALSE, \w+TryRegister|goto_if_set FLAG_DEFEATED_PETALBURG_GYM|"
                      r"special GetPlayerBigGuyGirlString", s):  # (the French texts do not use it)
            continue
        r = re.match(r"goto_if_eq VAR_RESULT, TRUE, (\w+)", s)
        if r:
            follow.append(r.group(1))
        out.append(line)
    text = "%s::\n%s\n" % (label, "\n".join(out))
    for f in follow:
        if f not in done:
            done.add(f)
            text += "\n" + convert(f, all_blocks[f], all_blocks, done)
    return text


def add_buried(em, mapdir, emname):
    """Emerald's buried trainers of the map, appended to its object_events (new local ids: nothing renumbers)."""
    ej = json.loads(read(em / "data/maps" / emname / "map.json"))
    path = mapdir / "map.json"
    text = read(path)
    added = []
    for o in ej["object_events"]:
        if o["trainer_type"] != "TRAINER_TYPE_BURIED" or '"script": "%s"' % rename(o["script"]) in text:
            continue
        added.append(o)
    if not added:
        return []
    rj = json.loads(text)
    for o in added:
        rj["object_events"].append({
            "type": "object", "graphics_id": o["graphics_id"].replace("OBJ_EVENT_GFX_", "OBJ_EVENT_GFX_HOENN_", 1),
            "x": o["x"], "y": o["y"], "elevation": o["elevation"], "movement_type": o["movement_type"],
            "movement_range_x": o["movement_range_x"], "movement_range_y": o["movement_range_y"],
            "trainer_type": o["trainer_type"], "trainer_sight_or_berry_tree_id": o["trainer_sight_or_berry_tree_id"],
            "script": rename(o["script"]), "flag": "0", "in_connection": False})
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(json.dumps(rj, indent=2, ensure_ascii=False) + "\n")
    return [rename(o["script"]) for o in added]


def buried_ids(mapdir):
    """(script, local id) of the map's buried trainers."""
    objs = json.loads(read(mapdir / "map.json"))["object_events"]
    return [(o["script"], i + 1) for i, o in enumerate(objs) if o["trainer_type"] == "TRAINER_TYPE_BURIED"]


def gen_scripts(em):
    stub_re = re.compile(r"^(\w+)::[ \t]+@ (trainer|NPC) #\d+ \((\d+),(\d+)\)(?: (TRAINER_\w+|no trainerbattle), "
                         r"Emerald (\w+) sight (\d+))?\n", re.M)
    em_all = {}
    for p in sorted((em / "data/maps").glob("*/scripts.inc")):
        em_all.update(blocks(rename(read(p))))
    done, touched = set(), []
    for scripts in sorted((REPO / "data/maps").glob("*/scripts.inc")):
        src = read(scripts)
        if "@ hoenn_import:" not in src:
            continue
        mapdir = scripts.parent
        emname = next((mapdir.name.replace(new, old, 1) for old, new in RENAMES.items()
                       if mapdir.name.startswith(new + "_")), mapdir.name)
        new, seen, sights = [], [], {}
        for s in stub_re.finditer(src):
            label = s.group(1)
            if label in done:  # converted on another map already: the stub would define it twice
                seen.append(s.group(0))
                continue
            if label not in em_all or s.group(2) == "NPC" and label not in TALK_TO_BATTLE:
                continue
            text = convert(label, em_all[label], em_all, done)
            if not text:
                continue
            done.add(label)
            seen.append(s.group(0))
            new.append(text)
            if s.group(2) == "trainer":
                sights[label] = (s.group(6), s.group(7))
        for label in add_buried(em, mapdir, emname):
            if label not in done:
                done.add(label)
                new.append(convert(label, em_all[label], em_all, done))
        if not new:
            continue
        em_src = read(em / "data/maps" / emname / "scripts.inc")
        bury = re.search(r"^%s_EventScript_CheckBuryTrainers::\n.*?^%s_EventScript_EndCheckBuryTrainers::\n\treturn\n"
                         % (emname, emname), em_src, re.M | re.S)
        if bury:  # Lavaridge Gym: on entering, the trainers not beaten yet are buried again
            lids = {o["script"]: o["local_id"] for o in json.loads(read(em / "data/maps" / emname / "map.json"))
                    ["object_events"] if o.get("local_id")}
            on = mapdir.name + "_OnTransition"
            src = "".join(".equ %s, %d\n" % (lids[s], n) for s, n in buried_ids(mapdir)) + "\n" + src
            src = re.sub(r"^@ hoenn_import: Emerald map scripts not ported: ON_TRANSITION \(\w+\)\n", "", src, flags=re.M)
            src = src.replace("%s_MapScripts::\n\t.byte 0\n" % mapdir.name,
                              "%s_MapScripts::\n\tmap_script MAP_SCRIPT_ON_TRANSITION, %s\n\t.byte 0\n\n%s:\n\tcall %s_"
                              "EventScript_CheckBuryTrainers\n\tend\n" % (mapdir.name, on, on, mapdir.name), 1)
            new.append(bury.group(0))
        for line in seen:
            src = src.replace(line, "", 1)
        # the stub group lost all its labels: drop its comment and its end
        src = re.sub(r"^@ hoenn_import: silent until scripted;[^\n]*\n\tend\n", "", src, flags=re.M)
        src = src.rstrip("\n") + "\n\n" + "\n".join(new)
        with open(scripts, "w", encoding="utf-8", newline="") as f:
            f.write(src)
        if sights:
            js = read(mapdir / "map.json")
            for label, (kind, sight) in sights.items():
                js, n = re.subn(r'"trainer_type": "TRAINER_TYPE_NONE",(\s*)"trainer_sight_or_berry_tree_id": "0",'
                                r'((?:\s*"[a-z_]+": [^\n]*\n)*?\s*"script": "%s")' % label,
                                r'"trainer_type": "TRAINER_TYPE_%s",\1"trainer_sight_or_berry_tree_id": "%s",\2'
                                % (kind, sight), js, count=1)
                assert n == 1, "%s: object of %s not found" % (mapdir.name, label)
            with open(mapdir / "map.json", "w", encoding="utf-8", newline="") as f:
                f.write(js)
        touched.append(emname)
        print("%s: %d scripts" % (mapdir.name, len(new)))
    print("Emerald maps touched:", " ".join(touched))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--emerald", type=Path, default=REPO.parent / "pokeemerald")
    parser.add_argument("--rom", type=Path, default=REPO / "Pokemon - Version Emeraude (FR).gba")
    parser.add_argument("--scripts", action="store_true", help="also replace the trainer stubs of the Hoenn maps")
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    gen_data(args.emerald.resolve(), args.rom.resolve())
    if args.scripts:
        gen_scripts(args.emerald.resolve())


if __name__ == "__main__":
    main()
