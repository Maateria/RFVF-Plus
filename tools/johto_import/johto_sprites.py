#!/usr/bin/env python3
"""Generate the PokemonHnS overworld sprites the Johto maps show (the OBJ_EVENT_GFX_JOHTO_* graphics ids).

Usage, from the repo root, before tools/johto_import/johto_import.py, then build as usual:
    uv run --no-project --with pillow python tools/johto_import/johto_sprites.py [--hns ../pokehns] [--check]

What is imported: every sprite a Johto object johto_import.py keeps shows (johto_import.needed_sprites): HnS's people and
objects (OBJ_EVENT_GFX_X_HNS -> OBJ_EVENT_GFX_JOHTO_X), and the Pokemon this repo has no overworld sprite of
(OBJ_EVENT_GFX_MON_BASE + SPECIES_X -> OBJ_EVENT_GFX_JOHTO_MON_X: HnS's follower sprite, its own palette). A Pokemon this
repo already draws keeps this repo's sprite (the user's rule), so does no other object.

GRAPHICS IDS ARE STORED IN SAVES: they live in the Johto block (512-767), append-only; palette tags too (0x1160..).
Johto layouts load HnS's 4 NPC palettes in the NPC slots (OBJ_PAL_MODE_JOHTO); every other palette (a special
character's, a Pokemon's, a Kanto or Hoenn sprite's) gets a free palette slot while it is shown (event_object_movement.c).

Written between "BEGIN/END generated by tools/johto_import/johto_sprites.py: <block>" lines, made after the matching
blocks of tools/hoenn_import/hoenn_sprites.py on the first run. Copies: graphics/object_events/pics/johto/**,
graphics/object_events/palettes/johto/*.pal.
"""
import argparse
import re
import shutil
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "hoenn_import"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from hoenn_sprites import cmds, defines, definitions, uncomment  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
TOOL = "generated by tools/johto_import/johto_sprites.py"
HOENN_TOOL = "generated by tools/hoenn_import/hoenn_sprites.py"
OBJ = "src/data/object_events/"
PICS = "graphics/object_events/pics/johto/"
PALS = "graphics/object_events/palettes/johto/"
JOHTO_IDS = range(512, 768)
FIRST_PAL_TAG, LAST_PAL_TAG = 0x1160, 0x11FE  # OBJ_EVENT_PAL_TAG_NONE is 0x11FF
FIXED_TAGS = {"OBJ_EVENT_PAL_TAG_NPC_%d_HNS" % n: "PALSLOT_NPC_%d" % n for n in range(1, 5)}  # OBJ_PAL_MODE_JOHTO
FEMALE = re.compile(r"(LASS|BEAUTY|TWIN|WOMAN_\d|GIRL_\d|LITTLE_GIRL|PICNICKER|SWIMMER_F|NURSE|MOM|OLD_WOMAN|KIMONO|"
                    r"SKIER_F|WORKER_F|ATTENDANT_F|BATTLE_GIRL|COOLTRAINER_F|SCIENTIST_F|ROCKET_F|CLAIR|WHITNEY|"
                    r"JASMINE|ARIANA|LINK_RECEPTIONIST|SABRINA|LYRA\w*|KRIS\w*|TEACHER|POKEFAN_F|GRANNY|BEAUTY)$")
MISC = re.compile(r"(ITEM_BALL|POKE_BALL|BREAKABLE_ROCK|CUTTABLE_TREE|PUSHABLE_BOULDER|FOSSIL|WHIRLPOOL|TOWER_BEAM|"
                  r"SS_AQUA|TRAIN_EAST|LEGENDARY_SHADOW|SMALL_LIGHT)$")


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def strip_own(text):
    return re.sub(r"^[ \t]*(//|#) BEGIN %s: ([^\n]*)\n.*?^[ \t]*\1 END %s: \2\n" % (re.escape(TOOL), re.escape(TOOL)),
                  "", text, flags=re.S | re.M)


def tables(text, ev):
    """{table: [anim by index]} of the `union AnimCmd *const` tables of `text`."""
    out = {}
    for name, (_, body) in definitions(text, r"union AnimCmd \*const").items():
        entries, i = {}, 0
        for item in (x.strip() for x in uncomment(body).split(",") if x.strip()):
            m = re.fullmatch(r"\[(.+?)\]\s*=\s*(\w+)", item)
            try:
                i = ev(m.group(1)) if m else i
            except (KeyError, SyntaxError, NameError):
                break
            entries[i] = m.group(2) if m else item
            i += 1
        else:
            if entries:
                out[name] = [entries.get(k) for k in range(max(entries) + 1)]
    return out


class HnSSprites:
    """What PokemonHnS has: graphics infos, pic tables, pictures, palettes, anims, species overworld data."""

    def __init__(self, root):
        self.root = root
        o = root / OBJ
        self.pointers = dict(re.findall(r"\[(OBJ_EVENT_GFX_\w+)\]\s*=\s*&(\w+)", read(o / "object_event_graphics_info_pointers.h")))
        self.infos = {}
        for n, body in re.findall(r"const struct ObjectEventGraphicsInfo (\w+) = \{(.*?)\};",
                                  uncomment(read(o / "object_event_graphics_info.h")), re.S):
            named = dict(re.findall(r"\.(\w+)\s*=\s*([^,\n]+?)\s*,", body + ","))
            if named:
                self.infos[n] = named
            else:
                v = [x.strip() for x in body.split(",") if x.strip()]
                keys = ["tileTag", "paletteTag", "reflectionPaletteTag", "size", "width", "height", "paletteSlot",
                        "shadowSize", "inanimate", "compressed", "tracks", "oam", "subspriteTables", "anims", "images",
                        "affineAnims"]
                self.infos[n] = dict(zip(keys, v))
        self.pic_tables = {}
        for f in ("object_event_pic_tables.h", "object_event_pic_tables_followers.h"):
            for n, (_, b) in definitions(read(o / f), "struct SpriteFrameImage").items():
                self.pic_tables[n] = re.findall(r"\b(overworld_frame|overworld_ascending_frames|obj_frame_tiles)\(([^)]*)\)", b)
        self.incbins = {}
        for f in (o / "object_event_graphics.h", root / "src/data/graphics/pokemon.h"):
            self.incbins.update(re.findall(r"const u(?:16|32) (\w+)\[\w*\]\s*=\s*INCBIN_(?:U16|U32|COMP)\(\"([^\"]+)\"\)", read(f)))
        mov = read(root / "src/event_object_movement.c")
        self.palettes = {t: s for s, t in re.findall(r"\{(gObjectEventPal_\w+),\s*(OBJ_EVENT_PAL_TAG_\w+)\}", mov)}
        anims = read(o / "object_event_anims.h")
        self.anims = {n: cmds(b) for n, (_, b) in definitions(anims, "union AnimCmd").items()}
        self.anim_defs = {n: d for n, (d, _) in definitions(anims, "union AnimCmd").items()}
        self.anim_tables = tables(anims, ev_of(root))
        self.table_text = {n: d for n, (d, _) in definitions(anims, r"union AnimCmd \*const").items()}
        self.rules = dict(re.findall(r"^\$\((?:OBJEVENTGFXDIR|POKEMONGFXDIR)\)/(\S+)\.4bpp: %\.4bpp: %\.png\n\t\$\(GFX\) \$< \$@ ([^\n]*)",
                                     read(root / "spritesheet_rules.mk"), re.M))
        self.overworld = {}  # SPECIES_X -> (pic table, size, shadow, tracks, anims, palette)
        for p in sorted((root / "src/data/pokemon/species_info").glob("*.h")):
            text = uncomment(read(p))
            for sp, body in re.findall(r"\[(SPECIES_\w+)\]\s*=\s*\{(.*?)\n    \},", text, re.S):
                m = re.search(r"\bOVERWORLD\(\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+)", body)
                if m and sp not in self.overworld:
                    self.overworld[sp] = m.groups()
        # species defined through a macro (UNOWN_MISC_INFO(letter, ...)): Unown A stands for Unown on a map
        self.overworld.setdefault("SPECIES_UNOWN", ("sPicTable_UnownA", "SIZE_32x32", "SHADOW_SIZE_M", "TRACKS_NONE",
                                                    "sAnimTable_Following", "gOverworldPalette_Unown"))

    def png_of(self, sym):
        return self.incbins[sym].replace(".4bpp.smol", ".png").replace(".4bpp.lz", ".png").replace(".4bpp", ".png")


def ev_of(root):
    texts = [read(p) for p in (root / "include/constants/event_object_movement.h", root / "include/event_object_movement.h")
             if p.exists()]
    return defines(*texts)


def camel(name):
    return "".join(w.capitalize() for w in name.lower().split("_"))


class Generator:
    def __init__(self, hns_root, needed):
        self.h = HnSSprites(hns_root)
        self.ids_text = read(REPO / "include/constants/event_objects.h")
        mov = read(REPO / "src/event_object_movement.c")
        self.here_anims_text = strip_own(read(REPO / OBJ / "object_event_anims.h"))
        self.here_anims = {n: cmds(b) for n, (_, b) in definitions(self.here_anims_text, "union AnimCmd").items()}
        self.here_tables = tables(self.here_anims_text, ev_of(REPO))
        self.here_defs = set(re.findall(r"#define\s+(\w+)", strip_own(self.ids_text) + "\n".join(
            read(p) for p in (REPO / "include/constants").glob("*.h"))))
        self.here_symbols = set(re.findall(r"\b(g\w+|s\w+)\[\]", read(REPO / OBJ / "base_oam.h") +
                                           read(REPO / OBJ / "object_event_subsprites.h"))) | set(
            re.findall(r"const struct OamData (\w+)", read(REPO / OBJ / "base_oam.h")))
        self.old_ids = {n: int(v) for n, v in re.findall(r"^#define (OBJ_EVENT_GFX_JOHTO_\w+)\s+(\d+)", self.ids_text, re.M)}
        self.old_tags = {n: int(v, 16) for n, v in re.findall(r"^#define (OBJ_EVENT_PAL_TAG_JOHTO_\w+)\s+(0x[0-9A-Fa-f]+)", mov, re.M)}
        self.scope = self.sprites(needed)

    def sprites(self, needed):
        """[(our gfx name, kind, HnS key)]: kind "info" (an HnS graphics info) or "mon" (a species' follower sprite)."""
        out = []
        for g in sorted(needed):
            mon = re.fullmatch(r"OBJ_EVENT_GFX_MON_BASE\s*\+\s*SPECIES_(\w+)", g)
            if mon:
                s = mon.group(1)
                if any(c in self.here_defs for c in ("OBJ_EVENT_GFX_" + s, "OBJ_EVENT_GFX_HOENN_" + s)):
                    continue  # this repo draws it already
                out.append(("OBJ_EVENT_GFX_JOHTO_MON_" + s, "mon", "SPECIES_" + s))
            else:
                if g in self.here_defs and not g.endswith("_HNS"):
                    continue
                out.append(("OBJ_EVENT_GFX_JOHTO_" + re.sub(r"_HNS$", "", g[len("OBJ_EVENT_GFX_"):]), "info", g))
        return out

    def assign(self, old, names, first, last):
        ids = dict(old)
        for n in names:
            if n not in ids:
                ids[n] = max(list(ids.values()) + [first - 1]) + 1
        assert max(ids.values(), default=first) <= last and len(set(ids.values())) == len(ids), "Johto block full"
        return ids

    def run(self):
        h = self.h
        missing = [k for _, kind, k in self.scope if kind == "mon" and k not in h.overworld]
        if missing:
            raise SystemExit("no OVERWORLD() data found in HnS for %s" % ", ".join(missing))
        self.ids = self.assign(self.old_ids, [g for g, _, _ in self.scope], JOHTO_IDS.start, JOHTO_IDS.stop - 1)
        rows, pals, pics, rules, copies, infos, ports, anim_choice = [], {}, {}, [], {}, [], {}, {}
        for gfx, kind, key in self.scope:
            short = gfx[len("OBJ_EVENT_GFX_JOHTO_"):]
            if kind == "info":
                info = dict(h.infos[h.pointers[key]])
                tag = info["paletteTag"]
                pal_sym = h.palettes[tag]
                pal_file = h.incbins[pal_sym].replace(".gbapal", ".pal")
                tag_here = "OBJ_EVENT_PAL_TAG_JOHTO_" + re.sub(r"_HNS$", "", tag[len("OBJ_EVENT_PAL_TAG_"):])
                frames_src = h.pic_tables[info["images"]]
                w, hgt = int(info["width"]), int(info["height"])
                anims, shadow, tracks, inanimate = info["anims"], info["shadowSize"], info["tracks"], info["inanimate"]
                oam, sub = info["oam"].lstrip("&"), info["subspriteTables"].replace("sOamTables_", "gObjectEventSpriteOamTables_")
                folder = "misc" if MISC.match(short) else "people"
            else:
                pic_table, size, shadow, tracks, anims, pal_sym = h.overworld[key]
                frames_src = h.pic_tables[pic_table]
                w = hgt = 32 if size == "SIZE_32x32" else 64
                pal_file = h.incbins[pal_sym].replace(".gbapal", ".pal")
                tag = tag_here = "OBJ_EVENT_PAL_TAG_JOHTO_" + short
                inanimate = "FALSE"
                oam, sub = "gObjectEventBaseOam_%dx%d" % (w, hgt), "gObjectEventSpriteOamTables_%dx%d" % (w, hgt)
                folder = "pokemon"
            if tracks not in self.here_defs:  # HnS's slither / spot tracks: none here
                tracks = "TRACKS_NONE"
            if shadow not in self.here_defs:  # SHADOW_SIZE_NONE: a shadow only shows under a jumping object
                shadow = "SHADOW_SIZE_S"
            for need in (oam, sub, shadow):
                if need not in self.here_symbols and need not in self.here_defs:
                    raise SystemExit("%s: %s does not exist here" % (gfx, need))
            # pictures: one sheet per HnS picture symbol
            lines = []
            for macro, args in frames_src:
                a = [x.strip() for x in args.split(",")]
                sym = a[0]
                if sym not in pics:
                    src = h.png_of(sym)
                    dst = PICS + folder + "/" + (Path(src).stem if folder != "pokemon" else Path(src).parent.name) + ".png"
                    assert dst not in copies.values(), dst
                    copies[src] = dst
                    pics[sym] = ("gObjectEventPic_Johto" + camel(short) if folder == "pokemon" else
                                 "gObjectEventPic_Johto" + camel(re.sub(r"_hns$", "", Path(src).stem)), dst)
                    rule = h.rules.get(src[len("graphics/object_events/pics/"):-4] if "object_events" in src
                                       else src[len("graphics/pokemon/"):-4])
                    if rule:
                        rules.append("$(OBJEVENTGFXDIR)/%s.4bpp: %%.4bpp: %%.png\n\t$(GFX) $< $@ %s\n\n"
                                     % (dst[len("graphics/object_events/pics/"):-4], rule))
                here_sym = pics[sym][0]
                if macro == "overworld_ascending_frames":
                    png = Image.open(h.root / h.png_of(sym))
                    n = png.width * png.height // (w * hgt)
                    lines += ["    overworld_frame(%s, %s, %s, %d),\n" % (here_sym, a[1], a[2], k) for k in range(n)]
                elif macro == "overworld_frame":
                    lines.append("    overworld_frame(%s, %s),\n" % (here_sym, ", ".join(a[1:])))
                else:
                    lines.append("    obj_frame_tiles(%s),\n" % here_sym)
            # anims: this repo's table with the same anims, else HnS's ported (sAnimTable_JohtoX)
            if anims not in anim_choice:
                anim_choice[anims] = self.anim_table(anims, ports)
            table_here, max_frame = anim_choice[anims]
            lines += [lines[0]] * (max_frame + 1 - len(lines))
            pic_table_here = "sPicTable_Johto" + camel(short)
            infos.append((gfx, short, pic_table_here, lines, dict(
                tileTag="TAG_NONE", paletteTag=tag_here, reflectionPaletteTag="OBJ_EVENT_PAL_TAG_NONE",
                size=str(w * hgt // 2), width=str(w), height=str(hgt),
                paletteSlot=FIXED_TAGS.get(tag, "PALSLOT_NPC_SPECIAL"), shadowSize=shadow, inanimate=inanimate,
                disableReflectionPaletteLoad="FALSE", tracks=tracks, oam="&" + oam, subspriteTables=sub,
                anims=table_here, images=pic_table_here, affineAnims="gDummySpriteAffineAnimTable")))
            pals[tag_here] = (pal_file, "gObjectEventPal_Johto" + camel(tag_here[len("OBJ_EVENT_PAL_TAG_JOHTO_"):]))
            color = ("NPC_TEXT_COLOR_MON" if folder == "pokemon" else "NPC_TEXT_COLOR_NEUTRAL" if folder == "misc"
                     else "NPC_TEXT_COLOR_FEMALE" if FEMALE.match(short) else "NPC_TEXT_COLOR_MALE")
            rows.append(dict(gfx=gfx, id=self.ids[gfx], color=color, tag=tag_here, size="%dx%d" % (w, hgt),
                             frames=len(lines), kind=kind))
        self.tags = self.assign(self.old_tags, sorted(pals), FIRST_PAL_TAG, LAST_PAL_TAG)
        self.rows, self.copies = rows, dict(copies)
        self.copies.update({src: PALS + Path(src).name.replace("overworld_normal", Path(src).parent.name)
                            if "pokemon/" in src else PALS + Path(src).name for src, _ in pals.values()})
        self.pal_files = {t: self.copies[src] for t, (src, _) in pals.items()}
        return self.blocks(rows, pals, pics, rules, infos, ports)

    def anim_table(self, name, ports):
        """(table name here, highest frame it shows)."""
        h = self.h
        hn = [h.anims[a] if a else None for a in h.anim_tables[name]]
        same = [n for n, t in self.here_tables.items() if len(t) >= len(hn)
                and all(a is None or (t[i] and self.here_anims.get(t[i]) == a) for i, a in enumerate(hn))]
        frames = max(args[0][1] for a in hn if a for c, args in a if c == "ANIMCMD_FRAME")
        if same:
            return min(same, key=lambda n: (n != name, len(self.here_tables[n]))), frames
        new = "sAnimTable_Johto" + re.sub(r"^sAnimTable_|_hns$", "", name)
        # entries at an index this repo does not have (expansion's ANIM_EXIT_POKEBALL_*) are left out
        text = re.sub(r"^[ \t]*\[(\w+)\]\s*=\s*\w+,[ \t]*(?://[^\n]*)?\r?\n",
                      lambda m: m.group(0) if m.group(1) in self.here_defs or m.group(1).isdigit() else "",
                      h.table_text[name], flags=re.M)
        for anim in dict.fromkeys(re.findall(r"\b(sAnim_\w+)\b", uncomment(text))):
            if self.here_anims.get(anim) == h.anims[anim]:
                continue
            renamed = "sAnim_Johto" + re.sub(r"^sAnim_|_hns$", "", anim)
            if renamed not in ports:
                ports[renamed] = re.sub(r"\b%s\b" % anim, renamed, h.anim_defs[anim])
            text = re.sub(r"\b%s\b" % anim, renamed, text)
        ports[new] = text.replace(name, new, 1)
        return new, frames

    def blocks(self, rows, pals, pics, rules, infos, ports):
        rows = sorted(rows, key=lambda r: r["id"])
        b = {}
        b["include/constants/event_objects.h", "ids"] = (
            "// PokemonHnS object graphics for Johto maps (tools/johto_import/johto_sprites.py). Append-only: SAVED\n"
            + "".join("#define %s %d\n" % (r["gfx"], r["id"]) for r in rows))
        b[OBJ + "object_event_graphics.h", "graphics"] = "".join(
            'const u16 %s[] = INCBIN_U16("%s");\n' % (sym, self.pal_files[t].replace(".pal", ".gbapal"))
            for t, (_, sym) in sorted(pals.items(), key=lambda kv: self.tags[kv[0]])) + "".join(
            'const u16 %s[] = INCBIN_U16("%s");\n' % (sym, dst.replace(".png", ".4bpp")) for sym, dst in pics.values())
        b[OBJ + "object_event_pic_tables.h", "pic tables"] = "".join(
            "static const struct SpriteFrameImage %s[] = {\n%s};\n\n" % (pt, "".join(lines))
            for _, _, pt, lines, _ in infos)
        b[OBJ + "object_event_anims.h", "anims"] = "\n".join(ports[n] for n in sorted(ports, key=lambda n: ("Table" in n, n)))
        keys = ["tileTag", "paletteTag", "reflectionPaletteTag", "size", "width", "height", "paletteSlot", "shadowSize",
                "inanimate", "disableReflectionPaletteLoad", "tracks", "oam", "subspriteTables", "anims", "images",
                "affineAnims"]
        b[OBJ + "object_event_graphics_info.h", "graphics infos"] = "".join(
            "const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_Johto%s = {\n%s};\n\n" % (
                camel(short), "".join("\t.%s = %s,\n" % (k, f[k]) for k in keys)) for _, short, _, _, f in infos)
        b[OBJ + "object_event_graphics_info_pointers.h", "declarations"] = "".join(
            "const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_Johto%s;\n" % camel(s) for _, s, _, _, _ in infos)
        b[OBJ + "object_event_graphics_info_pointers.h", "pointers"] = "".join(
            "    %-40s = &gObjectEventGraphicsInfo_Johto%s,\n" % ("[%s]" % g, camel(s)) for g, s, _, _, _ in infos)
        b["src/event_object_movement.c", "palette tags"] = "".join(
            "#define %-45s 0x%04X\n" % (t, v) for t, v in sorted(self.tags.items(), key=lambda kv: kv[1]))
        b["src/event_object_movement.c", "palettes"] = "".join(
            "    {%s%s},\n" % ((pals[t][1] + ",").ljust(40) + " ", t) for t in sorted(pals, key=self.tags.get))
        by_id = {r["id"]: r for r in rows}
        top = max(by_id) + 1 if by_id else JOHTO_IDS.start
        lines = []
        for even in range(JOHTO_IDS.start, top, 2):
            col = lambda i: by_id[i]["color"] if i in by_id else "NPC_TEXT_COLOR_NEUTRAL"
            key = "[%s / 2]" % by_id[even]["gfx"] if even in by_id else "[%d / 2]" % even
            lines.append("    %s= COLORS(%s, %s), // %s\n" % (key.ljust(50) + " ", col(even), col(even + 1),
                                                             by_id[even + 1]["gfx"] if even + 1 in by_id else "%d: none" % (even + 1)))
        b["src/dynamic_placeholder_text_util.c", "text colors"] = "".join(lines)
        b["spritesheet_rules.mk", "rules"] = "".join(rules)[:-1]
        return b


def splice(text, name, body, path):
    """`body` in this tool's block `name` of `text`; a block made after hoenn_sprites.py's of the same name."""
    c = "#" if path.endswith(".mk") else "//"
    body = body if body.endswith("\n") or not body else body + "\n"
    own = re.search(r"^([ \t]*)%s BEGIN %s: %s\n.*?^[ \t]*%s END %s: %s\n" % (
        c, re.escape(TOOL), re.escape(name), c, re.escape(TOOL), re.escape(name)), text, re.S | re.M)
    if own:
        ind = own.group(1)
        return text[:own.start()] + "%s%s BEGIN %s: %s\n%s%s%s END %s: %s\n" % (
            ind, c, TOOL, name, body, ind, c, TOOL, name) + text[own.end():]
    hoenn = re.search(r"^([ \t]*)%s END %s: %s\n" % (c, re.escape(HOENN_TOOL), re.escape(name)), text, re.M)
    assert hoenn, "%s: no hoenn_sprites block '%s' to put the Johto one after" % (path, name)
    ind = hoenn.group(1)
    new = "%s%s BEGIN %s: %s\n%s%s%s END %s: %s\n" % (ind, c, TOOL, name, body, ind, c, TOOL, name)
    return text[:hoenn.end()] + new + text[hoenn.end():]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--hns", type=Path, default=REPO.parent / "pokehns", help="PokemonHnS clone")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if a file would change")
    args = ap.parse_args()
    import johto_import as ji
    hns = ji.HnS(args.hns)
    order, _ = ji.select(hns)
    names, ids = ji.taken_names()
    needed = ji.needed_sprites(hns, [ji.JMap(hns, m, names, ids) for m in order])
    gen = Generator(args.hns, needed)
    blocks = gen.run()
    changed = []
    for path in dict.fromkeys(p for p, _ in blocks):
        text = read(REPO / path)
        new = text
        for (p, name), body in blocks.items():
            if p == path:
                new = splice(new, name, body, path)
        if path.endswith("event_objects.h"):  # highest id of every region + 1, the rule of hoenn_sprites.py too
            ids_all = [int(v) for v in re.findall(r"^#define OBJ_EVENT_GFX_\w+\s+(\d+)\s*(?://.*)?$", new, re.M)]
            new = re.sub(r"^(#define NUM_OBJ_EVENT_GFX\s+)\d+", lambda m: m.group(1) + str(max(ids_all) + 1), new, flags=re.M)
        if new != text:
            changed.append(path)
            if not args.check:
                with open(REPO / path, "w", encoding="utf-8", newline="") as f:
                    f.write(new)
    for src, dst in gen.copies.items():
        s = args.hns / src
        if not (REPO / dst).exists() or (REPO / dst).read_bytes() != s.read_bytes():
            changed.append(dst)
            if not args.check:
                (REPO / dst).parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(s, REPO / dst)
    wanted = {(REPO / d).resolve() for d in gen.copies.values()}
    for folder in ("graphics/object_events/pics/johto", "graphics/object_events/palettes/johto"):
        for p in (REPO / folder).rglob("*"):  # copies of sprites no object shows any more (and their build outputs)
            if p.is_file() and p.with_suffix(p.suffix if p.suffix in (".png", ".pal") else
                                             (".png" if p.suffix == ".4bpp" else ".pal")).resolve() not in wanted:
                changed.append(p.relative_to(REPO).as_posix())
                if not args.check:
                    p.unlink()
    rows = sorted(gen.rows, key=lambda r: r["id"])
    print("%d Johto sprites (%d people/objects, %d Pokemon), ids %d..%d; %d palettes" % (
        len(rows), sum(r["kind"] == "info" for r in rows), sum(r["kind"] == "mon" for r in rows),
        rows[0]["id"], rows[-1]["id"], len(gen.tags)))
    print(("would change: " if args.check else "changed: ") + ("%d files" % len(changed) if changed else "nothing"))
    if args.check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
